// Phase 2 tagging pass (overhaul). Adds equivalenceClass + calculatorFlag to every
// item, emits a within-bucket dedup report, bumps the graph schema version. The
// pure rules MIRROR the tested lib/item-certification (source of truth); the full
// certify() round-trip runs as the vitest gate (lib/item-certification/bank.test.ts).
// Reversible: backups/question-bank-2026-06-15.json is the byte-identical snapshot.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

// Paths relative to the repo root (this script lives in scripts/) — codexreview
// hardcoded-script-paths fix; runs from any clone/CI workspace.
const ROOT = fileURLToPath(new URL("..", import.meta.url));
const GRAPH = ROOT + "data/algebra1-graph.json";
const REPORT = ROOT + "phases/phase-2-dedup-report.md";

// Mirrors lib/item-certification (the tested source of truth): Unicode minus
// normalized first; numeric-set canonicalized order-insensitive.
const maskNumbers = (p) =>
  p.replace(/−/g, "-").replace(/-?\d+(?:\.\d+)?(?:\/\d+)?/g, "#").replace(/\s+/g, " ").trim().toLowerCase();
const answerResponse = (a) => (a.kind === "numeric-set" ? [...a.values].sort().join(", ") : a.value);
const equivalenceClassOf = (it) => `${it.skillId}|${it.answer.kind}|d${it.difficulty}|${maskNumbers(it.prompt)}`;
const calculatorFlagFor = (it) => (it.answer.kind === "numeric" ? "no_calculator" : "calc_neutral_arithmetic_light");

const graph = JSON.parse(readFileSync(GRAPH, "utf8"));
let total = 0, taggedEq = 0, taggedCalc = 0;
const all = [];
for (const node of graph.nodes) {
  if (!node.problems) continue;
  for (const phase of ["p1", "p2", "p3"]) {
    for (const it of node.problems[phase] ?? []) {
      total++;
      it.equivalenceClass = equivalenceClassOf(it);
      taggedEq++;
      it.calculatorFlag = calculatorFlagFor(it);
      taggedCalc++;
      all.push(it);
    }
  }
}

// Within-bucket exact dups only (node+phase+sport+prompt+answer). Cross-bucket
// same-prompt items are legitimate phase/sport coverage and are NOT grouped.
const byKey = new Map();
for (const it of all) {
  const key = `${it.skillId}|${it.phase}|${it.sport}|${it.prompt.trim().toLowerCase()}|${answerResponse(it.answer)}`;
  let arr = byKey.get(key);
  if (!arr) { arr = []; byKey.set(key, arr); }
  arr.push(it.id);
}
const dupGroups = [...byKey.entries()].filter(([, ids]) => ids.length > 1);
const dupExtra = dupGroups.reduce((s, [, ids]) => s + ids.length - 1, 0);

// Distinct structural families (equivalenceClass) for transfer interpretability.
const families = new Set(all.map(equivalenceClassOf));

const bump = (v) => { const p = v.split("."); p[1] = String(Number(p[1]) + 1); p[2] = "0"; return p.join("."); };
const prevVer = graph.schema?.version ?? "1.9.2";
if (graph.schema) graph.schema.version = bump(prevVer);

writeFileSync(GRAPH, JSON.stringify(graph, null, 2) + "\n", "utf8");

const report = `# Phase 2 — Dedup report (within-bucket exact only)

Generated by scripts/phase2-tag-bank.mjs. Snapshot: backups/question-bank-2026-06-15.json.

- Total items: ${total}
- equivalenceClass tagged: ${taggedEq} (100%)
- calculatorFlag tagged: ${taggedCalc} (100%)
- Distinct structural families (equivalenceClass): ${families.size}
- TRUE within-bucket exact-duplicate GROUPS (same node+phase+sport+prompt+answer): ${dupGroups.length}
- Redundant copies in those groups (collapse candidates): ${dupExtra}
- Graph schema.version: ${prevVer} -> ${graph.schema?.version}

> Cross-bucket same-prompt items (different phase/sport) are NOT counted — they are
> legitimate coverage (codexreview exact-dup-collapse). Collapse of the within-bucket
> groups below is a reviewed follow-up; tagging + the report land first so nothing is
> deleted blindly. Restore-by-diff against the snapshot if needed.

## Within-bucket duplicate groups (id lists)
${dupGroups.length === 0 ? "_none_" : dupGroups.map(([k, ids]) => `- \`${k.slice(0, 80)}\` → ${ids.join(", ")}`).join("\n")}
`;
writeFileSync(REPORT, report, "utf8");

console.log(`tagged ${total} items; ${families.size} families; ${dupGroups.length} within-bucket dup groups (${dupExtra} extra); schema.version ${prevVer} -> ${graph.schema?.version}`);
